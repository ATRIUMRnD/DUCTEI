    // ---- health + healer: each test breaks something on purpose and checks the answer ----

    fn cfg_with(rooms: &str) -> Config { toml::from_str(&format!("state = \"D:/x\"\n{rooms}")).unwrap() }

    fn room_status(h: Health, note: &str) -> crate::RoomStatus {
        crate::RoomStatus { health: h, kind: crate::Kind::External, pid: None, restarts: 0, since_unix: 0, note: note.into() }
    }

    const THREE_ROOMS: &str = "[[room]]\nname = \"sync\"\nprocess = \"s.exe\"\ntask = \"sync-serve\"\n[[room]]\nname = \"ward\"\nprocess = \"w.exe\"\n[[room]]\nname = \"loop\"\nkind = \"managed\"\nexe = \"l.exe\"\n";

    /// Reports with a healthy supervisor and the given state per room.
    fn rep(sync: u8, ward: u8, lp: u8, t: u64) -> Vec<spec::Health> {
        [(SUPERVISOR_ROOM, spec::HEALTH_OK), ("sync", sync), ("ward", ward), ("loop", lp)].iter()
            .map(|(n, s)| spec::Health { room: n.to_string(), state: *s, reason: (*s != spec::HEALTH_OK).then(|| "check failed".to_string()), checked_ms: t })
            .collect()
    }

    #[test]
    fn a_room_that_cannot_be_checked_is_never_reported_ok() {
        let cfg = cfg_with(THREE_ROOMS);
        let now = 1_000_000_000u64;
        let mut s = Status { unix: now / 1000, supervisor_pid: 7, ..Default::default() };
        s.rooms.insert("sync".into(), room_status(Health::Up, ""));
        s.rooms.insert("ward".into(), room_status(Health::Blocked, "waiting for sync"));
        let r = health_reports(&cfg, Ok(&s), now);
        let get = |n: &str| r.iter().find(|h| h.room == n).unwrap().clone();
        assert_eq!(r.len(), 4, "supervisor line plus one per configured room");
        assert_eq!((get(SUPERVISOR_ROOM).state, get("sync").state, get("sync").reason), (spec::HEALTH_OK, spec::HEALTH_OK, None));
        assert_eq!((get("ward").state, get("ward").reason.as_deref()), (spec::HEALTH_DEGRADED, Some("waiting for sync")));
        assert_eq!(get("loop").state, spec::HEALTH_DOWN, "no report from the supervisor is down, not ok");
        assert!(r.iter().all(|h| h.state == spec::HEALTH_OK || h.reason.is_some()), "every non-OK report says why");
        // Inside the silence window the supervisor still counts; past it everything is down.
        assert_eq!(health_reports(&cfg, Ok(&s), now + 5000)[0].state, spec::HEALTH_OK);
        let r = health_reports(&cfg, Ok(&s), now + 7000);
        assert!(r.iter().all(|h| h.state == spec::HEALTH_DOWN && h.reason.is_some()));
        assert!(r[0].reason.as_deref().unwrap().contains("silent for 7 s"), "{:?}", r[0].reason);
        // Status file gone or torn.
        let r = health_reports(&cfg, Err("gone"), now);
        assert!(r.iter().all(|h| h.state == spec::HEALTH_DOWN && h.reason.is_some()));
        // A clean `atrium down` is named as such.
        s.supervisor_pid = 0;
        assert_eq!(health_reports(&cfg, Ok(&s), now)[0].reason.as_deref(), Some(STOPPED_ON_PURPOSE));
    }

    #[test]
    fn healer_confirms_alerts_once_restarts_with_backoff_and_reports_recovery() {
        let cfg = cfg_with(THREE_ROOMS);
        let (ok, down) = (spec::HEALTH_OK, spec::HEALTH_DOWN);
        let mut h = Healer::default();
        // Healthy baseline: nothing to say.
        for t in [0, 1000, 2000, 3000] { assert_eq!(h.step(&cfg, &rep(ok, ok, ok, t), t), HealStep::default()); }
        // All three rooms drop at 4000; not confirmed until it has held 2 s.
        assert_eq!(h.step(&cfg, &rep(down, down, down, 4000), 4000), HealStep::default());
        assert_eq!(h.step(&cfg, &rep(down, down, down, 5000), 5000), HealStep::default());
        // Confirmed: three alerts, one restart (only the external room that names a task).
        let s = h.step(&cfg, &rep(down, down, down, 6000), 6000);
        assert_eq!(s.alerts.len(), 3, "{s:?}");
        assert!(s.alerts.iter().all(|(rec, t)| !rec && t.contains("DOWN: check failed")), "{s:?}");
        assert_eq!(s.restarts, vec!["sync".to_string()]);
        // Still down a second later: said once, tried once.
        assert_eq!(h.step(&cfg, &rep(down, ok, ok, 7000), 7000), HealStep::default());
        // ward and loop came back at 7000; confirmed and reported at 9000.
        let s = h.step(&cfg, &rep(down, ok, ok, 9000), 9000);
        assert_eq!(s.alerts.iter().filter(|(rec, t)| *rec && t.contains("is back after 5 s")).count(), 2, "{s:?}");
        assert!(s.restarts.is_empty());
        // Backoff: second try 30 s after the first, third 60 s after the second.
        assert!(h.step(&cfg, &rep(down, ok, ok, 35_999), 35_999).restarts.is_empty());
        assert_eq!(h.step(&cfg, &rep(down, ok, ok, 36_000), 36_000).restarts, vec!["sync".to_string()]);
        assert!(h.step(&cfg, &rep(down, ok, ok, 95_999), 95_999).restarts.is_empty());
        assert_eq!(h.step(&cfg, &rep(down, ok, ok, 96_000), 96_000).restarts.len(), 1);
        // It comes back: one recovery line with how long it was down.
        assert_eq!(h.step(&cfg, &rep(ok, ok, ok, 97_000), 97_000), HealStep::default());
        let s = h.step(&cfg, &rep(ok, ok, ok, 99_000), 99_000);
        assert_eq!(s.alerts, vec![(true, "RECOVERY sync is back after 95 s".to_string())]);
        // And the backoff starts over on the next outage.
        h.step(&cfg, &rep(down, ok, ok, 100_000), 100_000);
        assert_eq!(h.step(&cfg, &rep(down, ok, ok, 102_000), 102_000).restarts, vec!["sync".to_string()]);
    }

    #[test]
    fn a_short_blip_is_not_news_and_a_dead_supervisor_is_one_alert() {
        let cfg = cfg_with(THREE_ROOMS);
        let (ok, down) = (spec::HEALTH_OK, spec::HEALTH_DOWN);
        let mut h = Healer::default();
        // Down for one pass, back the next: nothing is sent, nothing is restarted.
        for (state, t) in [(ok, 0), (ok, 2000), (down, 3000), (ok, 4000), (ok, 5000), (ok, 6000)] {
            assert_eq!(h.step(&cfg, &rep(state, state, state, t), t), HealStep::default(), "t={t}");
        }
        // Supervisor stops reporting: one alert for it, none per room, and no
        // task is started for rooms that were simply not checked.
        let dead = |t: u64| health_reports(&cfg, Err("gone"), t);
        assert_eq!(h.step(&cfg, &dead(10_000), 10_000), HealStep::default());
        let s = h.step(&cfg, &dead(12_000), 12_000);
        assert_eq!(s.alerts, vec![(false, "HEALTH atrium DOWN: status unreadable: gone".to_string())]);
        assert!(s.restarts.is_empty());
        assert_eq!(h.step(&cfg, &dead(13_000), 13_000), HealStep::default());
    }
