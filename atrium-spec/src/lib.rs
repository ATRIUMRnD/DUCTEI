//! ATRIUM contract compiler.
//!
//! One TOML spec describes the constants and plain structs that DUCTEI (Rust),
//! Qallow (C) and LIMEN (Python) must agree on. This crate parses it and
//! emits matching code for all three, so a field renamed in one place (the
//! LIMEN #37 `fidelity_estimate` -> `success_probability` drift) fails
//! `atrium-spec check` at build time instead of the nightly smoke at 3am.
//!
//! Deliberately small: scalars, strings, fixed byte arrays, optional fields.
//! Anything richer belongs in the hand-written code that wraps these types.

use serde::Deserialize;
use std::fmt::Write as _;

#[derive(Debug, Deserialize)]
pub struct Spec {
    pub spec: Meta,
    #[serde(default, rename = "const")]
    pub consts: Vec<Const>,
    #[serde(default, rename = "struct")]
    pub structs: Vec<Struct>,
}

#[derive(Debug, Deserialize)]
pub struct Meta {
    pub name: String,
    pub version: u32,
}

#[derive(Debug, Deserialize)]
pub struct Const {
    pub name: String,
    #[serde(rename = "type")]
    pub ty: String,
    pub value: String,
    #[serde(default)]
    pub doc: Option<String>,
}

#[derive(Debug, Deserialize)]
pub struct Struct {
    pub name: String,
    #[serde(default)]
    pub doc: Option<String>,
    #[serde(default, rename = "field")]
    pub fields: Vec<Field>,
}

#[derive(Debug, Deserialize)]
pub struct Field {
    pub name: String,
    #[serde(rename = "type")]
    pub ty: String,
    #[serde(default)]
    pub optional: bool,
    #[serde(default)]
    pub doc: Option<String>,
}

/// The closed set of spec types.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Ty {
    U8,
    U16,
    U32,
    U64,
    I32,
    I64,
    F64,
    Bool,
    Str,
    Bytes(usize),
}

#[derive(Debug, PartialEq, Eq)]
pub enum SpecError {
    Toml(String),
    UnknownType { at: String, ty: String },
    Duplicate(String),
}

impl std::fmt::Display for SpecError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Toml(e) => write!(f, "spec is not valid TOML: {e}"),
            Self::UnknownType { at, ty } => write!(f, "{at}: unknown type `{ty}`"),
            Self::Duplicate(n) => write!(f, "duplicate name `{n}`"),
        }
    }
}

impl std::error::Error for SpecError {}

pub fn parse_ty(s: &str) -> Option<Ty> {
    Some(match s {
        "u8" => Ty::U8,
        "u16" => Ty::U16,
        "u32" => Ty::U32,
        "u64" => Ty::U64,
        "i32" => Ty::I32,
        "i64" => Ty::I64,
        "f64" => Ty::F64,
        "bool" => Ty::Bool,
        "string" => Ty::Str,
        _ => {
            let inner = s.strip_prefix("bytes[")?.strip_suffix(']')?;
            Ty::Bytes(inner.parse().ok()?)
        }
    })
}

/// Parse and validate a spec document.
pub fn parse(text: &str) -> Result<Spec, SpecError> {
    let spec: Spec = toml::from_str(text).map_err(|e| SpecError::Toml(e.to_string()))?;
    let mut names = std::collections::HashSet::new();
    for c in &spec.consts {
        if !names.insert(c.name.clone()) {
            return Err(SpecError::Duplicate(c.name.clone()));
        }
        parse_ty(&c.ty).ok_or_else(|| SpecError::UnknownType {
            at: c.name.clone(),
            ty: c.ty.clone(),
        })?;
    }
    for s in &spec.structs {
        if !names.insert(s.name.clone()) {
            return Err(SpecError::Duplicate(s.name.clone()));
        }
        let mut fields = std::collections::HashSet::new();
        for f in &s.fields {
            if !fields.insert(f.name.clone()) {
                return Err(SpecError::Duplicate(format!("{}.{}", s.name, f.name)));
            }
            parse_ty(&f.ty).ok_or_else(|| SpecError::UnknownType {
                at: format!("{}.{}", s.name, f.name),
                ty: f.ty.clone(),
            })?;
        }
    }
    Ok(spec)
}

fn header(spec: &Spec, comment: &str) -> String {
    format!(
        "{comment} GENERATED by atrium-spec from {}.toml v{}. Do not edit; edit the spec.\n\n",
        spec.spec.name, spec.spec.version
    )
}

// ---------------------------------------------------------------- Rust

fn rust_ty(t: Ty) -> String {
    match t {
        Ty::U8 => "u8".into(),
        Ty::U16 => "u16".into(),
        Ty::U32 => "u32".into(),
        Ty::U64 => "u64".into(),
        Ty::I32 => "i32".into(),
        Ty::I64 => "i64".into(),
        Ty::F64 => "f64".into(),
        Ty::Bool => "bool".into(),
        Ty::Str => "String".into(),
        Ty::Bytes(n) => format!("[u8; {n}]"),
    }
}

pub fn emit_rust(spec: &Spec) -> String {
    let mut o = header(spec, "//");
    o.push_str("#![allow(dead_code)]\nuse serde::{Deserialize, Serialize};\n\n");
    for c in &spec.consts {
        if let Some(d) = &c.doc {
            let _ = writeln!(o, "/// {d}");
        }
        let t = parse_ty(&c.ty).unwrap();
        match t {
            Ty::Str => {
                let _ = writeln!(o, "pub const {}: &str = {:?};", c.name, c.value);
            }
            _ => {
                let _ = writeln!(o, "pub const {}: {} = {};", c.name, rust_ty(t), c.value);
            }
        }
    }
    for s in &spec.structs {
        o.push('\n');
        if let Some(d) = &s.doc {
            let _ = writeln!(o, "/// {d}");
        }
        o.push_str("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n");
        let _ = writeln!(o, "pub struct {} {{", s.name);
        for f in &s.fields {
            if let Some(d) = &f.doc {
                let _ = writeln!(o, "    /// {d}");
            }
            let t = rust_ty(parse_ty(&f.ty).unwrap());
            if f.optional {
                o.push_str("    #[serde(default, skip_serializing_if = \"Option::is_none\")]\n");
                let _ = writeln!(o, "    pub {}: Option<{t}>,", f.name);
            } else {
                let _ = writeln!(o, "    pub {}: {t},", f.name);
            }
        }
        o.push_str("}\n");
    }
    o
}

// ---------------------------------------------------------------- C

fn c_ty(t: Ty) -> &'static str {
    match t {
        Ty::U8 => "uint8_t",
        Ty::U16 => "uint16_t",
        Ty::U32 => "uint32_t",
        Ty::U64 => "uint64_t",
        Ty::I32 => "int32_t",
        Ty::I64 => "int64_t",
        Ty::F64 => "double",
        Ty::Bool => "bool",
        Ty::Str => "const char *",
        Ty::Bytes(_) => "uint8_t",
    }
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, ch) in name.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

pub fn emit_c(spec: &Spec) -> String {
    let guard = format!("{}_SPEC_H", spec.spec.name.to_ascii_uppercase());
    let mut o = format!(
        "/* GENERATED by atrium-spec from {}.toml v{}. Do not edit; edit the spec. */\n\n",
        spec.spec.name, spec.spec.version
    );
    let _ = writeln!(o, "#ifndef {guard}\n#define {guard}\n#include <stdint.h>\n#include <stdbool.h>\n");
    for c in &spec.consts {
        let t = parse_ty(&c.ty).unwrap();
        let doc = c.doc.as_deref().map(|d| format!(" /* {d} */")).unwrap_or_default();
        match t {
            Ty::Str => {
                let _ = writeln!(o, "#define {} {:?}{doc}", c.name, c.value);
            }
            Ty::U32 | Ty::U16 | Ty::U8 => {
                let _ = writeln!(o, "#define {} ({}u){doc}", c.name, c.value);
            }
            Ty::U64 => {
                let _ = writeln!(o, "#define {} ({}ull){doc}", c.name, c.value);
            }
            _ => {
                let _ = writeln!(o, "#define {} ({}){doc}", c.name, c.value);
            }
        }
    }
    for s in &spec.structs {
        o.push('\n');
        if let Some(d) = &s.doc {
            let _ = writeln!(o, "/* {d} */");
        }
        o.push_str("typedef struct {\n");
        for f in &s.fields {
            let t = parse_ty(&f.ty).unwrap();
            let mut notes = Vec::new();
            if f.optional {
                notes.push("optional: see has_<field>".to_string());
            }
            if let Some(d) = &f.doc {
                notes.push(d.clone());
            }
            let note = if notes.is_empty() {
                String::new()
            } else {
                format!(" /* {} */", notes.join("; "))
            };
            match t {
                Ty::Bytes(n) => {
                    let _ = writeln!(o, "    uint8_t {}[{n}];{note}", f.name);
                }
                _ => {
                    let _ = writeln!(o, "    {} {};{note}", c_ty(t), f.name);
                }
            }
            if f.optional {
                let _ = writeln!(o, "    bool has_{};", f.name);
            }
        }
        let _ = writeln!(o, "}} {}_t;", snake(&s.name));
    }
    let _ = writeln!(o, "\n#endif /* {guard} */");
    o
}

// ---------------------------------------------------------------- Python

fn py_ty(t: Ty) -> &'static str {
    match t {
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::U64 | Ty::I32 | Ty::I64 => "int",
        Ty::F64 => "float",
        Ty::Bool => "bool",
        Ty::Str => "str",
        Ty::Bytes(_) => "bytes",
    }
}

pub fn emit_python(spec: &Spec) -> String {
    let mut o = header(spec, "#");
    o.push_str("from __future__ import annotations\nfrom dataclasses import dataclass\nfrom typing import Optional\n\n");
    for c in &spec.consts {
        let t = parse_ty(&c.ty).unwrap();
        let doc = c.doc.as_deref().map(|d| format!("  # {d}")).unwrap_or_default();
        match t {
            Ty::Str => {
                let _ = writeln!(o, "{}: str = {:?}{doc}", c.name, c.value);
            }
            _ => {
                let _ = writeln!(o, "{}: int = {}{doc}", c.name, c.value);
            }
        }
    }
    for s in &spec.structs {
        o.push_str("\n\n@dataclass(frozen=True)\n");
        let _ = writeln!(o, "class {}:", s.name);
        if let Some(d) = &s.doc {
            let _ = writeln!(o, "    \"\"\"{d}\"\"\"");
        }
        // Required fields first: dataclasses reject a default before a non-default.
        for f in s.fields.iter().filter(|f| !f.optional) {
            let _ = writeln!(o, "    {}: {}", f.name, py_ty(parse_ty(&f.ty).unwrap()));
        }
        for f in s.fields.iter().filter(|f| f.optional) {
            let _ = writeln!(o, "    {}: Optional[{}] = None", f.name, py_ty(parse_ty(&f.ty).unwrap()));
        }
        if s.fields.is_empty() {
            o.push_str("    pass\n");
        }
    }
    o
}

/// Every output file this spec produces, as (relative path, contents).
pub fn emit_all(spec: &Spec) -> Vec<(String, String)> {
    let n = &spec.spec.name;
    vec![
        (format!("{n}_spec.rs"), emit_rust(spec)),
        (format!("{n}_spec.h"), emit_c(spec)),
        (format!("{n}_spec.py"), emit_python(spec)),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    const SPEC: &str = r#"
[spec]
name = "t"
version = 1
[[const]]
name = "MAGIC"
type = "u32"
value = "0x10"
[[const]]
name = "SCOPE"
type = "string"
value = "a.b"
[[struct]]
name = "Cert"
[[struct.field]]
name = "job_id"
type = "string"
[[struct.field]]
name = "target_met"
type = "bool"
optional = true
[[struct.field]]
name = "node"
type = "bytes[16]"
"#;

    #[test]
    fn parses_and_emits_all_three_languages() {
        let s = parse(SPEC).unwrap();
        let rs = emit_rust(&s);
        assert!(rs.contains("pub const MAGIC: u32 = 0x10;"));
        assert!(rs.contains("pub const SCOPE: &str = \"a.b\";"));
        assert!(rs.contains("pub target_met: Option<bool>,"));
        assert!(rs.contains("pub node: [u8; 16],"));
        let c = emit_c(&s);
        assert!(c.contains("#define MAGIC (0x10u)"));
        assert!(c.contains("uint8_t node[16];"));
        assert!(c.contains("bool has_target_met;"));
        assert!(c.contains("} cert_t;"));
        let py = emit_python(&s);
        assert!(py.contains("class Cert:"));
        assert!(py.contains("target_met: Optional[bool] = None"));
        // required before optional, or Python refuses the dataclass
        assert!(py.find("job_id: str").unwrap() < py.find("target_met").unwrap());
    }

    #[test]
    fn rejects_unknown_type_and_duplicates() {
        let bad = SPEC.replace("type = \"bytes[16]\"", "type = \"blob\"");
        assert!(matches!(parse(&bad), Err(SpecError::UnknownType { .. })));
        let dup = format!("{SPEC}\n[[struct]]\nname = \"Cert\"\n");
        assert_eq!(parse(&dup).err(), Some(SpecError::Duplicate("Cert".into())));
    }

    #[test]
    fn snake_case_for_c_typedefs() {
        assert_eq!(snake("CertSummary"), "cert_summary");
        assert_eq!(snake("QswHello"), "qsw_hello");
    }

    #[test]
    fn output_is_deterministic() {
        let s = parse(SPEC).unwrap();
        assert_eq!(emit_all(&s), emit_all(&s));
    }
}
